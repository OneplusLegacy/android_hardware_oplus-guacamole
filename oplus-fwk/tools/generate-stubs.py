"""Generate com.oneplus.inner.* compatibility stubs for the 7 Pro stock camera.

The stock OnePlus 7 Pro camera (com.oneplus.camera 7.2.47) references 134
com.oneplus.inner.* types across its three APKs. They are not part of AOSP, not
part of the stock 7 Pro framework and not part of oplus-support-wrapper.jar:
oplus-support-wrapper.jar defines com.oplus.inner.* instead, a different
package. The com.oneplus.inner classes ship in a separately distributed
"OnePlus dynamic wrapper" APK that is gated behind ro.sys.oneplus.support.

Every code path that reaches those wrappers is already guarded by
com.oneplus.utils.Utils.isWrapperSupport(), which returns false when the
property is unset, and then falls back to reflection. The stock 7 Pro wrapper
version also predates the 10.11.0 baseline the camera asks for, so even with
the wrapper installed the reflection path is what runs.

The classes still have to exist for ART verification: a field or method
signature naming a missing type fails class linking with NoClassDefFoundError
before any guard can run.

Each generated member keeps the shape the calling dex actually uses:
  - invoke-static          -> static method
  - invoke-virtual         -> instance method
  - invoke-interface       -> method on an interface-declared type
  - invoke-direct <init>   -> constructor
  - iget/iput              -> instance field
  - sget/sput              -> static field
  - .implements            -> the type is an interface
  - .super                 -> the type is a non-final class

Getting this wrong produces IncompatibleClassChangeError, NoSuchMethodError,
NoSuchFieldError or VerifyError at link time, so the kinds are read straight
from the invoke opcodes in the camera dex rather than guessed.

The input model is produced by extract-inner-refs.py, which walks baksmali
output and records every reference. Run that first:

    ./extract-inner-refs.py --smali <dir> --out inner_model.json
    ./generate-stubs.py --model inner_model.json \
                        --platform-jar <system android.jar> \
                        --out ./oplus-fwk/src

Unlike an earlier version of this script, types in com.oneplus.inner are
always considered present: they are the very types being generated. Only
platform types that AOSP removed cause a member to be dropped, because a
signature naming them cannot compile.
"""

import argparse
import json
import re
from pathlib import Path

JAVA_KEYWORDS = {
    'abstract', 'assert', 'boolean', 'break', 'byte', 'case', 'catch', 'char',
    'class', 'const', 'continue', 'default', 'do', 'double', 'else', 'enum',
    'extends', 'final', 'finally', 'float', 'for', 'goto', 'if', 'implements',
    'import', 'instanceof', 'int', 'interface', 'long', 'native', 'new',
    'package', 'private', 'protected', 'public', 'return', 'short', 'static',
    'strictfp', 'super', 'switch', 'synchronized', 'this', 'throw', 'throws',
    'transient', 'try', 'void', 'volatile', 'while',
}

PRIMITIVES = {
    'Z': 'boolean', 'B': 'byte', 'C': 'char', 'S': 'short',
    'I': 'int', 'J': 'long', 'F': 'float', 'D': 'double', 'V': 'void',
}

DEFAULT_VALUES = {
    'boolean': 'false', 'byte': '(byte) 0', 'char': "'\\0'", 'short': '(short) 0',
    'int': '0', 'long': '0L', 'float': '0f', 'double': '0d',
}

INNER_PREFIX = 'com.oneplus.inner.'

HEADER = '''/*
 * Copyright (C) 2026 The LineageOS Project
 *
 * SPDX-License-Identifier: Apache-2.0
 *
 * Generated by generate-stubs.py. Do not edit by hand.
 */
package %s;

/**
 * Verification-only stub for a OnePlus dynamic wrapper %s.
 *
 * <p>See generate-stubs.py for why this type exists. It is never meant to
 * be executed: every call is guarded by
 * {@code com.oneplus.utils.Utils.isWrapperSupport()} in the caller and the
 * stock 7 Pro builds use the reflection fallback instead.
 *
 * <p>Members keep the static/instance/constructor shape the calling dex
 * actually uses, so class linking succeeds even though the bodies never
 * run.
 */
'''


def descriptor_to_java(desc):
    """Convert a JVM type descriptor to a Java source type."""
    desc = desc.strip()
    dims = 0
    while desc.startswith('['):
        dims += 1
        desc = desc[1:]

    if desc in PRIMITIVES:
        base = PRIMITIVES[desc]
    elif desc.startswith('L') and desc.endswith(';'):
        base = desc[1:-1].replace('/', '.').replace('$', '.')
    else:
        base = 'java.lang.Object'

    return base + '[]' * dims


def split_params(desc):
    """Split a method descriptor's parameter list into raw descriptors."""
    desc = desc.strip()
    if not desc:
        return []
    out = []
    i = 0
    while i < len(desc):
        start = i
        while desc[i] == '[':
            i += 1
        if desc[i] == 'L':
            i = desc.index(';', i) + 1
        else:
            i += 1
        out.append(desc[start:i])
    return out


def parse_signature(sig):
    """'name(desc)ret' -> (name, [param descriptors], ret descriptor)."""
    name, rest = sig.split('(', 1)
    close = rest.index(')')
    return name, split_params(rest[:close]), rest[close + 1:]


def safe_identifier(name):
    return name + '_' if name in JAVA_KEYWORDS else name


def package_and_simple(fqn):
    if '.' in fqn:
        pkg, simple = fqn.rsplit('.', 1)
        return pkg, simple
    return '', fqn


def model_key_to_fqn(key):
    """Model keys are relative to com.oneplus.inner; make them absolute."""
    return INNER_PREFIX + key.replace('/', '.')


class PlatformTypes:
    """Answers whether a type referenced by a stub exists on the platform.

    A wrapper method whose signature names a platform type that AOSP removed
    (for example android.hardware.fingerprint.FingerprintManager, dropped
    after API 28) cannot be declared at all: javac fails before the stub is
    ever verified. Such members are dropped, which is safe because the camera
    cannot call them either - the argument type does not exist.

    Types in com.oneplus.inner are always treated as present: they are
    generated by this same run, so a member naming one is never dropped.
    """

    def __init__(self, jar_paths):
        import zipfile

        self.entries = set()
        for jar_path in jar_paths or []:
            with zipfile.ZipFile(jar_path) as jar:
                self.entries |= {n[:-6].replace('/', '.')
                                 for n in jar.namelist()
                                 if n.endswith('.class')}
        self.enabled = bool(self.entries)

    def has(self, java_type):
        base = java_type.replace('[]', '')
        if base in DEFAULT_VALUES or base == 'void':
            return True
        if base.startswith(INNER_PREFIX):
            return True
        if not self.enabled:
            return True
        candidate = base
        while True:
            if candidate in self.entries:
                return True
            if '.' not in candidate:
                return False
            head, _, tail = candidate.rpartition('.')
            candidate = head + '$' + tail

    def blocks(self, types):
        """Return the types among `types` that the platform does not have."""
        return [t for t in types
                if t != 'void' and not self.has(t)]


def resolve_extends(cls, supers, interfaces, declares_method):
    """Pick what this class extends, if anything.

    A stub that another class .implements must be an interface; a stub that
    another class .super's must be a concrete non-final class. The camera
    always extends the stub to intercept callbacks, so the parent has to stay
    extendable even though every method body throws.
    """
    if cls in interfaces:
        return None
    return None


def render_member(entry, indent, owner, platform):
    """Render one method, or return [] when its signature cannot compile."""
    kind = entry['kind']
    name = entry['name']
    params = entry['params']
    ret = entry['ret']

    java_ret = descriptor_to_java(ret)
    arg_types = [descriptor_to_java(p) for p in params]

    if platform.blocks([java_ret] + arg_types):
        return []

    pad = '    ' * indent
    inner = '    ' * (indent + 1)

    if kind == 'constructor':
        ctor_args = ', '.join('%s a%d' % (t, i)
                              for i, t in enumerate(arg_types))
        return [
            '%spublic %s(%s) {' % (pad, owner, ctor_args),
            '%s// Verification-only stub; the camera never instantiates a' % inner,
            '%s// wrapper type directly.' % inner,
            '%s}' % pad,
        ]

    arg_list = ', '.join('%s a%d' % (t, i) for i, t in enumerate(arg_types))
    modifier = 'public static' if kind == 'static' else 'public'
    return [
        '%s%s %s %s(%s) {' % (pad, modifier, java_ret,
                              safe_identifier(name), arg_list),
        '%sthrow new UnsupportedOperationException(' % inner,
        '%s        "%s.%s is a verification-only stub");'
        % (inner, owner, name),
        '%s}' % pad,
    ]


def render_field(entry, indent):
    """Render one field, or return [] when its type cannot compile."""
    name, jtype, kind = entry
    modifier = 'public static' if kind == 'static' else 'public'
    pad = '    ' * indent
    default = DEFAULT_VALUES.get(jtype.rstrip('[]'))
    if default is not None:
        init = ' = ' + default
    else:
        init = ''
    return ['%s%s %s %s%s;' % (pad, modifier, jtype, safe_identifier(name), init)]


def render_class_body(cls, model, indent, platform):
    """Render the fields and methods declared directly on `cls`."""
    pad = '    ' * indent
    lines = []

    for name, ftype in model['fields'].get(cls, []):
        jtype = descriptor_to_java(ftype)
        if platform.blocks([jtype]):
            continue
        kind = model['kinds'].get(cls, {}).get('#|%s|%s' % (name, ftype),
                                              'instance')
        block = render_field((name, jtype, kind), indent)
        if block:
            lines.extend(block)
            lines.append('')

    for name, sig in model['methods'].get(cls, []):
        mname, params, ret = parse_signature(name + sig)
        key = '%s|%s' % (name, sig)
        kind = model['kinds'].get(cls, {}).get(key, 'instance')
        entry = {'name': mname, 'params': params, 'ret': ret, 'kind': kind}
        block = render_member(entry, indent, cls.split('/')[-1].split('$')[-1],
                              platform)
        if block:
            lines.extend(block)
            lines.append('')
    return lines


def render_stub_class(cls, model, indent, platform):
    """Render `cls` and, recursively, the nested types declared under it."""
    pad = '    ' * indent
    simple = cls.split('/')[-1].split('$')[-1]
    is_iface = cls in model['interfaces']
    is_super = cls in model['supers']

    if is_iface:
        head = '%spublic interface %s {' % (pad, simple)
    elif is_super:
        # Not final: com.oneplus.compat.* extends it to intercept callbacks.
        head = '%spublic static class %s {' % (pad, simple)
    else:
        head = '%spublic static final class %s {' % (pad, simple)

    lines = [head, '']
    lines.extend(render_class_body(cls, model, indent + 1, platform))

    has_children = any(t.startswith(cls + '$') for t in model['types'])
    if (not model['methods'].get(cls) and not model['fields'].get(cls)
            and not has_children):
        inner = '    ' * (indent + 1)
        if is_iface:
            lines.append(inner + '// No members were referenced by the camera.')
        else:
            lines.append('%sprivate %s() {' % (inner, simple))
            lines.append('%sthrow new UnsupportedOperationException(' % inner)
            lines.append('%s        "%s is a verification-only stub");'
                         % (inner, simple))
            lines.append(inner + '}')
        lines.append('')

    # Nested types, one level down.
    prefix = cls + '$'
    children = sorted(t for t in model['types']
                      if t.startswith(prefix) and '$' not in t[len(prefix):])
    for child in children:
        lines.extend(render_stub_class(child, model, indent + 1, platform))
        lines.append('')

    while lines and lines[-1] == '':
        lines.pop()
    lines.append(pad + '}')
    lines.append('')
    return lines


def render_outer(outer, model, platform):
    pkg, simple = package_and_simple(model_key_to_fqn(outer))
    is_iface = outer in model['interfaces']
    is_super = outer in model['supers']

    lines = HEADER % (pkg, 'interface' if is_iface else 'class')
    lines = lines.split('\n')

    if is_iface:
        head = 'public interface %s {' % simple
    elif is_super:
        head = 'public class %s {' % simple
    else:
        head = 'public final class %s {' % simple
    lines.append(head)
    lines.append('')

    lines.extend(render_class_body(outer, model, 1, platform))

    has_children = any(t.startswith(outer + '$') for t in model['types'])
    if (not model['methods'].get(outer) and not model['fields'].get(outer)
            and not has_children):
        if is_iface:
            lines.append('    // No members were referenced by the camera.')
        else:
            lines.append('    private %s() {' % simple)
            lines.append('        throw new UnsupportedOperationException(')
            lines.append('                "%s is a verification-only stub");' % simple)
            lines.append('    }')
        lines.append('')

    prefix = outer + '$'
    children = sorted(t for t in model['types']
                      if t.startswith(prefix) and '$' not in t[len(prefix):])
    for child in children:
        lines.extend(render_stub_class(child, model, 1, platform))
        lines.append('')

    while lines and lines[-1] == '':
        lines.pop()
    lines.append('}')
    lines.append('')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', required=True,
                        help='JSON produced by extract-inner-refs.py')
    parser.add_argument('--platform-jar', action='append', default=[],
                        help='android.jar used to drop removed types; repeatable')
    parser.add_argument('--out', required=True,
                        help='Java source root (oplus-fwk/src)')
    args = parser.parse_args()

    model = json.loads(Path(args.model).read_text())
    platform = PlatformTypes(args.platform_jar)
    if args.platform_jar and not platform.enabled:
        print('WARNING: --platform-jar produced no entries; type pruning off')

    # Every referenced type needs a stub, not just the ones that carry
    # members: PackageWrapper and PackageUserStateWrapper only ever appear in
    # signatures, and a missing type there fails javac for the caller.
    declared = (set(model['types']) | set(model['methods'])
                | set(model['fields']) | set(model['interfaces'])
                | set(model['supers']))
    roots = sorted({t.split('$')[0] for t in declared})

    out_root = Path(args.out)
    written = 0
    for root in roots:
        pkg, simple = package_and_simple(model_key_to_fqn(root))
        target = out_root / pkg.replace('.', '/') / (simple + '.java')
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_outer(root, model, platform))
        written += 1

    print('wrote %d stub sources under %s' % (written, out_root))


if __name__ == '__main__':
    main()
